// d2d_system_top - verification top: Die A and Die B connected through two lane
// channel models with fault injection (lane_fault_inj). Single power-on reset rst_n is
// synchronized separately into every clock domain inside the dies.
// Ports: three asynchronous clocks, rst_n, Die A AXI4 slave (s_axi_*), Die B AXI4 master
// (m_axi_*), APB3 per die (apb_a_*, apb_b_*), irq_a/irq_b, fault-injection inputs
// fi_{a2b,b2a}_{xor,drop} (clk_link domain), lane observation outputs mon_*.
module d2d_system_top #(
    parameter integer REPLAY_DEPTH   = 16,
    parameter integer CREDITS_REQ    = 16,
    parameter integer CREDITS_RSP    = 16,
    parameter integer TX_FIFO_DEPTH  = 8,
    parameter integer REPLAY_TIMEOUT = 256,
    parameter integer TRAIN_GOOD     = 8,
    parameter integer TRAIN_TIMEOUT  = 1024,
    parameter integer STABLE_CYCLES  = 2048
) (
    input  logic        clk_axi_a,
    input  logic        clk_axi_b,
    input  logic        clk_link,
    input  logic        rst_n,
    input  logic [3:0]   s_axi_awid,
    input  logic [31:0]  s_axi_awaddr,
    input  logic [7:0]   s_axi_awlen,
    input  logic [2:0]   s_axi_awsize,
    input  logic [1:0]   s_axi_awburst,
    input  logic         s_axi_awvalid,
    output logic         s_axi_awready,
    input  logic [63:0]  s_axi_wdata,
    input  logic [7:0]   s_axi_wstrb,
    input  logic         s_axi_wlast,
    input  logic         s_axi_wvalid,
    output logic         s_axi_wready,
    output logic [3:0]   s_axi_bid,
    output logic [1:0]   s_axi_bresp,
    output logic         s_axi_bvalid,
    input  logic         s_axi_bready,
    input  logic [3:0]   s_axi_arid,
    input  logic [31:0]  s_axi_araddr,
    input  logic [7:0]   s_axi_arlen,
    input  logic [2:0]   s_axi_arsize,
    input  logic [1:0]   s_axi_arburst,
    input  logic         s_axi_arvalid,
    output logic         s_axi_arready,
    output logic [3:0]   s_axi_rid,
    output logic [63:0]  s_axi_rdata,
    output logic [1:0]   s_axi_rresp,
    output logic         s_axi_rlast,
    output logic         s_axi_rvalid,
    input  logic         s_axi_rready,
    input  logic         apb_a_psel,
    input  logic         apb_a_penable,
    input  logic         apb_a_pwrite,
    input  logic [7:0]   apb_a_paddr,
    input  logic [31:0]  apb_a_pwdata,
    output logic [31:0]  apb_a_prdata,
    output logic         apb_a_pready,
    output logic         apb_a_pslverr,
    output logic         irq_a,
    output logic [3:0]   m_axi_awid,
    output logic [31:0]  m_axi_awaddr,
    output logic [7:0]   m_axi_awlen,
    output logic [2:0]   m_axi_awsize,
    output logic [1:0]   m_axi_awburst,
    output logic         m_axi_awvalid,
    input  logic         m_axi_awready,
    output logic [63:0]  m_axi_wdata,
    output logic [7:0]   m_axi_wstrb,
    output logic         m_axi_wlast,
    output logic         m_axi_wvalid,
    input  logic         m_axi_wready,
    input  logic [3:0]   m_axi_bid,
    input  logic [1:0]   m_axi_bresp,
    input  logic         m_axi_bvalid,
    output logic         m_axi_bready,
    output logic [3:0]   m_axi_arid,
    output logic [31:0]  m_axi_araddr,
    output logic [7:0]   m_axi_arlen,
    output logic [2:0]   m_axi_arsize,
    output logic [1:0]   m_axi_arburst,
    output logic         m_axi_arvalid,
    input  logic         m_axi_arready,
    input  logic [3:0]   m_axi_rid,
    input  logic [63:0]  m_axi_rdata,
    input  logic [1:0]   m_axi_rresp,
    input  logic         m_axi_rlast,
    input  logic         m_axi_rvalid,
    output logic         m_axi_rready,
    input  logic         apb_b_psel,
    input  logic         apb_b_penable,
    input  logic         apb_b_pwrite,
    input  logic [7:0]   apb_b_paddr,
    input  logic [31:0]  apb_b_pwdata,
    output logic [31:0]  apb_b_prdata,
    output logic         apb_b_pready,
    output logic         apb_b_pslverr,
    output logic         irq_b,
    input  logic [31:0] fi_a2b_xor,
    input  logic        fi_a2b_drop,
    input  logic [31:0] fi_b2a_xor,
    input  logic        fi_b2a_drop,
    output logic        mon_a2b_sof,
    output logic        mon_a2b_valid,
    output logic        mon_b2a_sof,
    output logic        mon_b2a_valid
);
  logic [31:0] a_tx_data, b_tx_data, a_rx_data, b_rx_data;
  logic        a_tx_valid, a_tx_sof, b_tx_valid, b_tx_sof;
  logic        a_rx_valid, a_rx_sof, b_rx_valid, b_rx_sof;
  logic        rl_n;

  reset_sync u_rs_link (.clk(clk_link), .rst_in_n(rst_n), .rst_out_n(rl_n));

  die_a_top #(.REPLAY_DEPTH(REPLAY_DEPTH), .CREDITS_REQ(CREDITS_REQ), .CREDITS_RSP(CREDITS_RSP), .TX_FIFO_DEPTH(TX_FIFO_DEPTH), .REPLAY_TIMEOUT(REPLAY_TIMEOUT), .TRAIN_GOOD(TRAIN_GOOD), .TRAIN_TIMEOUT(TRAIN_TIMEOUT), .STABLE_CYCLES(STABLE_CYCLES)) u_die_a (
      .clk_axi(clk_axi_a),
      .rst_axi_n(rst_n),
      .clk_link(clk_link),
      .rst_link_n(rst_n),
      .s_axi_awid(s_axi_awid),
      .s_axi_awaddr(s_axi_awaddr),
      .s_axi_awlen(s_axi_awlen),
      .s_axi_awsize(s_axi_awsize),
      .s_axi_awburst(s_axi_awburst),
      .s_axi_awvalid(s_axi_awvalid),
      .s_axi_awready(s_axi_awready),
      .s_axi_wdata(s_axi_wdata),
      .s_axi_wstrb(s_axi_wstrb),
      .s_axi_wlast(s_axi_wlast),
      .s_axi_wvalid(s_axi_wvalid),
      .s_axi_wready(s_axi_wready),
      .s_axi_bid(s_axi_bid),
      .s_axi_bresp(s_axi_bresp),
      .s_axi_bvalid(s_axi_bvalid),
      .s_axi_bready(s_axi_bready),
      .s_axi_arid(s_axi_arid),
      .s_axi_araddr(s_axi_araddr),
      .s_axi_arlen(s_axi_arlen),
      .s_axi_arsize(s_axi_arsize),
      .s_axi_arburst(s_axi_arburst),
      .s_axi_arvalid(s_axi_arvalid),
      .s_axi_arready(s_axi_arready),
      .s_axi_rid(s_axi_rid),
      .s_axi_rdata(s_axi_rdata),
      .s_axi_rresp(s_axi_rresp),
      .s_axi_rlast(s_axi_rlast),
      .s_axi_rvalid(s_axi_rvalid),
      .s_axi_rready(s_axi_rready),
      .apb_psel(apb_a_psel),
      .apb_penable(apb_a_penable),
      .apb_pwrite(apb_a_pwrite),
      .apb_paddr(apb_a_paddr),
      .apb_pwdata(apb_a_pwdata),
      .apb_prdata(apb_a_prdata),
      .apb_pready(apb_a_pready),
      .apb_pslverr(apb_a_pslverr),
      .irq(irq_a),
      .lane_tx_data(a_tx_data),
      .lane_tx_valid(a_tx_valid),
      .lane_tx_sof(a_tx_sof),
      .lane_rx_data(a_rx_data),
      .lane_rx_valid(a_rx_valid),
      .lane_rx_sof(a_rx_sof)
  );

  die_b_top #(.REPLAY_DEPTH(REPLAY_DEPTH), .CREDITS_REQ(CREDITS_REQ), .CREDITS_RSP(CREDITS_RSP), .TX_FIFO_DEPTH(TX_FIFO_DEPTH), .REPLAY_TIMEOUT(REPLAY_TIMEOUT), .TRAIN_GOOD(TRAIN_GOOD), .TRAIN_TIMEOUT(TRAIN_TIMEOUT), .STABLE_CYCLES(STABLE_CYCLES)) u_die_b (
      .clk_axi(clk_axi_b),
      .rst_axi_n(rst_n),
      .clk_link(clk_link),
      .rst_link_n(rst_n),
      .m_axi_awid(m_axi_awid),
      .m_axi_awaddr(m_axi_awaddr),
      .m_axi_awlen(m_axi_awlen),
      .m_axi_awsize(m_axi_awsize),
      .m_axi_awburst(m_axi_awburst),
      .m_axi_awvalid(m_axi_awvalid),
      .m_axi_awready(m_axi_awready),
      .m_axi_wdata(m_axi_wdata),
      .m_axi_wstrb(m_axi_wstrb),
      .m_axi_wlast(m_axi_wlast),
      .m_axi_wvalid(m_axi_wvalid),
      .m_axi_wready(m_axi_wready),
      .m_axi_bid(m_axi_bid),
      .m_axi_bresp(m_axi_bresp),
      .m_axi_bvalid(m_axi_bvalid),
      .m_axi_bready(m_axi_bready),
      .m_axi_arid(m_axi_arid),
      .m_axi_araddr(m_axi_araddr),
      .m_axi_arlen(m_axi_arlen),
      .m_axi_arsize(m_axi_arsize),
      .m_axi_arburst(m_axi_arburst),
      .m_axi_arvalid(m_axi_arvalid),
      .m_axi_arready(m_axi_arready),
      .m_axi_rid(m_axi_rid),
      .m_axi_rdata(m_axi_rdata),
      .m_axi_rresp(m_axi_rresp),
      .m_axi_rlast(m_axi_rlast),
      .m_axi_rvalid(m_axi_rvalid),
      .m_axi_rready(m_axi_rready),
      .apb_psel(apb_b_psel),
      .apb_penable(apb_b_penable),
      .apb_pwrite(apb_b_pwrite),
      .apb_paddr(apb_b_paddr),
      .apb_pwdata(apb_b_pwdata),
      .apb_prdata(apb_b_prdata),
      .apb_pready(apb_b_pready),
      .apb_pslverr(apb_b_pslverr),
      .irq(irq_b),
      .lane_tx_data(b_tx_data),
      .lane_tx_valid(b_tx_valid),
      .lane_tx_sof(b_tx_sof),
      .lane_rx_data(b_rx_data),
      .lane_rx_valid(b_rx_valid),
      .lane_rx_sof(b_rx_sof)
  );

  lane_fault_inj u_ch_a2b (
      .clk(clk_link), .rst_n(rl_n), .in_data(a_tx_data), .in_valid(a_tx_valid), .in_sof(a_tx_sof),
      .fi_xor(fi_a2b_xor), .fi_drop(fi_a2b_drop),
      .out_data(b_rx_data), .out_valid(b_rx_valid), .out_sof(b_rx_sof)
  );
  lane_fault_inj u_ch_b2a (
      .clk(clk_link), .rst_n(rl_n), .in_data(b_tx_data), .in_valid(b_tx_valid), .in_sof(b_tx_sof),
      .fi_xor(fi_b2a_xor), .fi_drop(fi_b2a_drop),
      .out_data(a_rx_data), .out_valid(a_rx_valid), .out_sof(a_rx_sof)
  );

  // the fault agent aligns flit-level faults on the transmitter's sof
  assign mon_a2b_sof   = a_tx_sof;
  assign mon_a2b_valid = a_tx_valid;
  assign mon_b2a_sof   = b_tx_sof;
  assign mon_b2a_valid = b_tx_valid;
endmodule
