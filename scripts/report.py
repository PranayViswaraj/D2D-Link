#!/usr/bin/env python3
"""Merge functional coverage from regression runs and generate docs from logs only.

Inputs : logs/regress/<cfg>/cov/*.json, logs/regress/<cfg>/*.json, logs/regress/summary.md,
         logs/formal_summary.txt, syn/reports/summary.txt
Outputs: docs/coverage_report.md, logs/coverage_merged.json, logs/results_numbers.json
"""
import glob
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REG = ROOT / "logs" / "regress"

# bins that are unreachable by construction (explained in the report)
EXPLAIN = {
    ("d2d.ltssm.arc", "('TRAIN', 'FAILED')"):
        "Initial TRAIN only fails if the peer never trains; every test keeps both dies enabled "
        "at start-up, so the failure path is exercised from RETRAIN instead.",
}


def merge():
    merged = defaultdict(lambda: defaultdict(int))
    files = sorted(glob.glob(str(REG / "*" / "cov" / "*.json")))
    for f in files:
        for item, bins in json.loads(Path(f).read_text()).items():
            for b, h in bins.items():
                merged[item][b] += h
    return merged, files


def main():
    merged, files = merge()
    (ROOT / "logs" / "coverage_merged.json").write_text(json.dumps(merged, indent=1))
    rows, tot_b, tot_h, holes = [], 0, 0, []
    for item in sorted(merged):
        bins = merged[item]
        hit = sum(1 for h in bins.values() if h > 0)
        tot_b += len(bins)
        tot_h += hit
        rows.append((item, hit, len(bins), 100.0 * hit / len(bins)))
        for b, h in bins.items():
            if h == 0:
                holes.append((item, b))
    overall = 100.0 * tot_h / tot_b if tot_b else 0.0

    results = [json.loads(Path(f).read_text()) for f in glob.glob(str(REG / "*" / "*.json"))]
    nums = dict(coverage_pct=round(overall, 1), bins_hit=tot_h, bins_total=tot_b, cov_files=len(files),
                transactions=sum(r.get("transactions", 0) for r in results),
                faults=sum(r.get("faults_total", 0) for r in results),
                replays=sum(r["counters_a"]["replay_cnt"] + r["counters_b"]["replay_cnt"] for r in results),
                naks=sum(r["counters_a"]["nak_cnt"] + r["counters_b"]["nak_cnt"] for r in results),
                timeouts=sum(r["counters_a"]["timeout_cnt"] + r["counters_b"]["timeout_cnt"] for r in results),
                retrains=sum(r["counters_a"]["retrain_cnt"] + r["counters_b"]["retrain_cnt"] for r in results),
                crc_errors=sum(r["counters_a"]["crc_err_cnt"] + r["counters_b"]["crc_err_cnt"] for r in results),
                runs_with_results=len(results))
    (ROOT / "logs" / "results_numbers.json").write_text(json.dumps(nums, indent=1))

    L = ["# Functional Coverage Report", "",
         "Generated by `scripts/report.py` from the per-run coverage databases in `logs/regress/*/cov/` "
         f"({len(files)} runs merged). Coverage is cocotb-coverage functional coverage; a bin counts as "
         "covered when it was hit at least once in any run.", "",
         f"**Overall: {tot_h}/{tot_b} bins = {overall:.1f}%**", "",
         "| Coverage item | Bins hit | Bins | % |", "|---|---|---|---|"]
    L += [f"| `{i}` | {h} | {n} | {p:.1f} |" for i, h, n, p in rows]
    L += ["", "## Uncovered bins", ""]
    if not holes:
        L.append("None.")
    else:
        L += ["| Item | Bin | Explanation |", "|---|---|---|"]
        for item, b in holes:
            why = EXPLAIN.get((item, b), "Not reached by the current stimulus in the time box (see notes).")
            L.append(f"| `{item}` | `{b}` | {why} |")
    L += ["", "## Notes", "",
          "- Cross `d2d.axi.len_x_idgrp` uses 4 ID groups (ID[3:2]) x 16 lengths = 64 bins; the full "
          "16x16 len x ID cross was reduced to fit the regression time box. `d2d.axi.kind_x_id` covers "
          "all 16 IDs for both reads and writes.",
          "- Error types are restricted to the CRC-16 guaranteed-detection envelope "
          "(<= 3 random bit flips, bursts <= 16 bits); undetectable patterns are a residual-error-rate "
          "question, not a functional one (see spec limitations)."]
    (ROOT / "docs" / "coverage_report.md").write_text("\n".join(L) + "\n")
    print(json.dumps(nums, indent=1))
    print(f"coverage {overall:.1f}% ({tot_h}/{tot_b}), holes: {len(holes)}")
    for h in holes[:40]:
        print("  hole:", h)


if __name__ == "__main__":
    main()
